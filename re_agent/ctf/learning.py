"""
Learning Mode Report Generator

Generates educational reports that explain the reverse process,
not just output the flag. Designed for users who want to learn
reverse engineering methodology.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any


def generate_learning_report(
    profile: dict,
    solve_result: dict,
    solver_runs: list[dict],
    output_dir: Path,
) -> Path:
    """Generate an educational Markdown report explaining the solve process"""

    lines = _build_learning_report(profile, solve_result, solver_runs)
    report_path = output_dir / "learning_report.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    return report_path


def _build_learning_report(
    profile: dict,
    solve_result: dict,
    solver_runs: list[dict],
) -> list[str]:
    solved = solve_result.get("verified", False)
    winning = solve_result.get("winning_candidate", {})
    method = solve_result.get("method", "unknown")

    lines = [
        "# Auto-Reverse Learning Report",
        "",
        "## What happened?",
        "",
        _describe_solve_process(profile, solved, winning, method),
        "",
        "## How was this solved?",
        "",
        _describe_solution_method(method, winning, solver_runs),
        "",
        "## Key Evidence",
        "",
        _list_key_evidence(profile),
        "",
        "## Solver Timeline",
        "",
        "| Step | Solver | Status | Why |",
        "|------|--------|--------|-----|",
    ]

    for i, sr in enumerate(solver_runs, 1):
        status = sr.get("status", "?")
        name = sr.get("solver", "?")
        why = _solver_rationale(name, status, profile)
        lines.append(f"| {i} | {name} | {status} | {why} |")

    lines.extend([
        "",
        "## How to solve similar challenges next time?",
        "",
        _generate_advice(profile, method),
        "",
        "## Key Takeaways",
        "",
    ])

    takeaways = _generate_takeaways(profile, method, solved)
    for t in takeaways:
        lines.append(f"- {t}")

    lines.extend([
        "",
        "## Tools Used",
        "",
        _list_tools_used(profile),
        "",
        "---",
        "",
        f"*Report generated by Auto-Reverse. SHA256: {profile.get('sha256', '?')[:16]}...*",
    ])

    return lines


def _describe_solve_process(
    profile: dict,
    solved: bool,
    winning: dict | None,
    method: str,
) -> str:
    file_type = profile.get("file_type", "unknown")
    arch = profile.get("architecture", "unknown")
    input_channels = profile.get("input_channels", [])
    comparison_hints = profile.get("comparison_hints", [])
    crypto_hints = profile.get("crypto_hints", [])

    parts = [f"This is a **{file_type}** binary (architecture: {arch})."]

    if input_channels:
        parts.append(f"It reads input via **{', '.join(input_channels)}**.")

    if comparison_hints:
        parts.append(f"It uses comparison APIs: **{', '.join(comparison_hints)}**.")

    if crypto_hints:
        parts.append(f"Crypto hints detected: **{', '.join(crypto_hints)}**.")

    if solved:
        parts.append(f"The flag was found using the **{method}** solver.")
        if winning:
            channel = winning.get("validation_mode", winning.get("input_channel", "unknown"))
            parts.append(f"The correct input is provided via **{channel}**.")
    else:
        parts.append("The flag was **not found** in this attempt.")
        parts.append("Review the solver timeline below for failed strategies.")

    return " ".join(parts)


def _describe_solution_method(
    method: str,
    winning: dict | None,
    solver_runs: list[dict],
) -> str:
    descriptions = {
        "static_flag": "The flag was found directly in the binary's strings without any decoding needed.",
        "encoding": "The flag was encoded (e.g., base64, hex, xor) in the binary and was decoded by trying multiple encoding schemes.",
        "dynamic_trace": "The program compares user input to the expected value at runtime. By hooking comparison functions (strcmp, memcmp), the correct value was extracted.",
        "z3_constraints": "The program validates input byte-by-byte using arithmetic constraints. These were encoded as Z3 constraints and solved.",
        "z3_extractor": "Byte-level constraints were automatically extracted from the decompiled code and solved with Z3.",
        "angr_path": "Symbolic execution traced all paths to find an input that reaches the success branch.",
        "dynamic_trace:ltrace": "ltrace was used to intercept comparison function calls and extract the expected arguments.",
        "dynamic_trace:frida": "Frida was used to hook comparison APIs at runtime.",
        "z3_extractor:llm": "LLM assisted in extracting constraints from decompiled pseudocode, which were then solved with Z3.",
    }
    return descriptions.get(method, f"The flag was found using the {method} solver.")


def _list_key_evidence(profile: dict) -> str:
    parts = []
    tags = profile.get("tags", [])

    if "has_success_string" in tags:
        success = profile.get("success_strings", [])
        if success:
            parts.append(f"Success strings found: `{success[0]}`")
    if "has_failure_string" in tags:
        failure = profile.get("failure_strings", [])
        if failure:
            parts.append(f"Failure strings found: `{failure[0]}`")
    if profile.get("comparison_hints"):
        parts.append(f"Comparison APIs: `{', '.join(profile['comparison_hints'])}`")
    if profile.get("encoding_hints"):
        parts.append(f"Encoding indicators: `{', '.join(profile['encoding_hints'])}`")
    if profile.get("protections"):
        parts.append(f"Protections: `{', '.join(profile['protections'])}`")

    if not parts:
        parts.append("No key evidence found. Try enabling Ghidra for deeper analysis.")

    return "\n".join(f"- {p}" for p in parts)


def _solver_rationale(name: str, status: str, profile: dict) -> str:
    rationales = {
        "static_flag": "Always check for plaintext flags first (cheapest operation).",
        "encoding": "Check if flag is encoded with common schemes.",
        "dynamic_trace": "Hook comparison APIs to observe expected values at runtime.",
        "z3_constraints": "Solve byte-level arithmetic constraints.",
        "z3_extractor": "Auto-extract constraints from decompiled code.",
        "angr_path": "Use symbolic execution to find path to success branch.",
    }

    if status == "skipped":
        return f"Skipped - {rationales.get(name, 'not applicable')}"
    if status == "error":
        return f"Failed - {rationales.get(name, 'attempted')}"
    if status == "ok":
        return f"Ran - {rationales.get(name, 'executed')}"
    return f"{status}"


def _generate_advice(profile: dict, method: str) -> str:
    comparison_hints = profile.get("comparison_hints", [])
    crypto_hints = profile.get("crypto_hints", [])
    encoding_hints = profile.get("encoding_hints", [])
    protections = profile.get("protections", [])

    advice = []

    if comparison_hints:
        advice.append(
            f"When you see **{', '.join(comparison_hints[:3])}** in imports:\n"
            f"  1. Run ltrace or Frida to hook comparison calls.\n"
            f"  2. If the expected value is hidden, decompile the check function.\n"
            f"  3. Extract per-byte transformations.\n"
            f"  4. Use Z3 or a small script to reverse.\n"
            f"  5. Validate in sandbox."
        )

    if crypto_hints:
        advice.append(
            f"When crypto operations like **{', '.join(crypto_hints[:3])}** are detected:\n"
            f"  1. Identify the algorithm from constants.\n"
            f"  2. Check if the key is hardcoded or derived.\n"
            f"  3. For XOR-based: try single-byte and repeating-key XOR.\n"
            f"  4. For block ciphers: implement decryption with the extracted key."
        )

    if encoding_hints:
        advice.append(
            f"When encoded data is detected:\n"
            f"  1. Try common encodings: base64, hex, rot13, URL decode.\n"
            f"  2. For XOR: try single-byte (0x00-0xFF) and repeating-key.\n"
            f"  3. Try multi-layer decoding (e.g., hex -> base64 -> plain).\n"
            f"  4. Look for custom base alphabet (base64 variants)."
        )

    if "has_comparison" in profile.get("tags", []):
        advice.append(
            "For comparison-based challenges:\n"
            "  1. Dynamic trace first (cheap and often solves directly).\n"
            "  2. If dynamic fails, decompile the comparison function.\n"
            "  3. Extract constraints for Z3 or write a small Python script.\n"
            "  4. Always verify in sandbox."
        )

    if protections:
        advice.append(
            f"When anti-analysis protections are detected (**{', '.join(protections[:3])}**):\n"
            "  1. For anti-debug (ptrace): hook or patch the check.\n"
            "  2. For UPX packing: use upx -d to unpack first.\n"
            "  3. For stripped binaries: run function identification first."
        )

    if not advice:
        advice.append(
            "General approach for unknown challenges:\n"
            "  1. Run strings and look for flag-like patterns.\n"
            "  2. Check imports for comparison and input APIs.\n"
            "  3. Use dynamic trace to observe runtime behavior.\n"
            "  4. Decompile key functions for deeper analysis."
        )

    return "\n\n".join(advice)


def _generate_takeaways(
    profile: dict,
    method: str,
    solved: bool,
) -> list[str]:
    takeaways = []

    if solved:
        takeaways.append(f"**{method}** solver was the key to this challenge.")
    else:
        takeaways.append("This challenge was not solved. Review failed strategies below.")

    comparison_hints = profile.get("comparison_hints", [])
    if comparison_hints:
        takeaways.append(
            f"Detecting **{comparison_hints[0]}** in imports is a strong signal "
            "that dynamic trace or Z3 will be useful."
        )

    encoding_hints = profile.get("encoding_hints", [])
    if encoding_hints:
        takeaways.append(
            f"Encoding hint **{encoding_hints[0]}** triggered the decoding solver."
        )

    success = profile.get("success_strings", [])
    if success:
        takeaways.append(
            f"Success string **\"{success[0]}\"** provides a search target for angr symbolic execution."
        )

    if profile.get("input_channels"):
        takeaways.append(
            f"Input arrives via **{', '.join(profile['input_channels'])}** — "
            "this determines whether to use argv or stdin for verification."
        )

    if not takeaways:
        takeaways.append("Always profile the binary first to understand its input method and structure.")

    return takeaways


def _list_tools_used(profile: dict) -> str:
    tools = ["strings (string extraction)"]
    if profile.get("comparison_hints"):
        tools.append("ltrace / Frida (dynamic trace)")
    if profile.get("solver_hints"):
        if "z3_constraints" in profile["solver_hints"]:
            tools.append("Z3 (constraint solver)")
        if "angr_path" in profile["solver_hints"]:
            tools.append("angr (symbolic execution)")
    tools.append("Docker sandbox (flag validation)")
    return "\n".join(f"- {t}" for t in tools)
