/* XOR Single Byte Challenge - flag is xor'd with 0x23 */
#include <stdio.h>
#include <string.h>

int main() {
    char flag[] = {
        0x6a, 0x6c, 0x60, 0x68, 0x4b, 0x71, 0x77, 0x75,
        0x43, 0x75, 0x70, 0x68, 0x6c, 0x7f, 0x71, 0x7d,
        0x43, 0x6a, 0x6c, 0x60, 0x68, 0x4b, 0x6d, 0x7e,
        0x0
    };

    for (int i = 0; i < strlen(flag); i++) {
        flag[i] ^= 0x23;
    }

    printf("Decoded: %s\n", flag);
    return 0;
}
